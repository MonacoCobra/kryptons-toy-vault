FLOOR = "1980-01-01"

def F(rid, name, subtitle, line, company, release, msrp, scale, demand, tags):
    if release < FLOOR:
        release = FLOOR
    return {
        "id": rid, "name": name, "subtitle": subtitle, "line": line,
        "company": company, "kind": "figure", "releaseDate": release,
        "msrp": float(msrp), "scale": scale, "demand": float(demand),
        "tags": [t for t in tags.split(",") if t], "source": "curated",
    }

def expand(prefix, line, company, scale, msrp, tag, rows):
    # rows: (suffix, name, subtitle, date, demand=1.0)
    out = []
    for r in rows:
        suf, name, sub, date = r[0], r[1], r[2], r[3]
        demand = r[4] if len(r) > 4 else 1.0
        out.append(F(f"{prefix}-{suf}", name, sub, line, company, date, msrp, scale, demand, tag))
    return out

